"""Export paper summaries from the kitchingroup-papers crucible into the site.

The crucible (~/Dropbox/kitchingroup-papers, not in this repo) holds an
LLM-distilled org-mode wiki of the group's papers. Run this on your machine
after distilling, then render and commit the result:

    python3 scripts/export_crucible.py [path/to/crucible/project]

It writes
  papers/<citekey>/index.qmd        one page per summary article
  papers/topics/<concept>/index.qmd one page per concept article
  data/papers-index.json            {doi: url}, used for "Summary" links on
                                    the publications page

Only text and bibliographic data are exported; the PDFs never leave the
crucible. Files this script generated earlier (marked with GENERATED) are
removed first, so deleting an article in the crucible removes its page.
"""

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAPERS = ROOT / "papers"
GENERATED = "<!-- GENERATED by scripts/export_crucible.py; edit the crucible, not this file -->"
CITE = re.compile(r"\b(citep|citet|citealp|citeauthor|citeyear|cite):([\w:.-]+(?:,[\w:.-]+)*)")
# Pandoc's org reader treats "/path" links as files, so internal links go
# through it as absolute URLs and are made root-relative again afterwards.
SITE = "https://kitchingroup.cheme.cmu.edu"
FILE_LINK = re.compile(r"\[\[file:([^\]]+?\.org)\](?:\[([^\]]*)\])?\]")


def parse_org(path):
    text = path.read_text()
    meta = {k.lower(): v.strip() for k, v in re.findall(r"^#\+(\w+):(.*)$", text, re.M)}
    props = dict(re.findall(r"^:([A-Z_]+):[ \t]*(.*)$", text.split(":END:")[0], re.M))
    # Body: everything after the first heading's property drawer.
    body = text.split(":END:", 1)[1] if ":END:" in text else text
    tags = [t for t in meta.get("filetags", "").split(":") if t]
    return meta.get("title", path.stem), props, tags, body.strip()


def bib_entries(bibfile):
    """cite key -> {doi, short} from the crucible's references.bib."""
    out = {}
    if not bibfile.exists():
        return out
    for m in re.finditer(r"@\w+\{([^,\s]+),(.*?)(?=\n@|\Z)", bibfile.read_text(), re.S):
        key, body = m.group(1), m.group(2)
        doi = re.search(r"\bdoi\s*=\s*[{\"]([^}\"]+)", body, re.I)
        year = re.search(r"\byear\s*=\s*[{\"]?(\d{4})", body, re.I)
        author = re.search(r"\bauthor\s*=\s*[{\"](.+?)[}\"]\s*,\s*\w+\s*=", body, re.I | re.S)
        first = ""
        if author:
            a = author.group(1).split(" and ")[0].strip()
            first = a.split(",")[0].strip() if "," in a else a.split()[-1]
        n_auth = len(author.group(1).split(" and ")) if author else 1
        short = f"{first}{' et al.' if n_auth > 2 else ''} {year.group(1) if year else ''}".strip()
        out[key] = {"doi": doi.group(1).strip() if doi else "", "short": short or key}
    return out


def link_citations(text, bib, summaries):
    def one(key, kind):
        b = bib.get(key, {"doi": "", "short": key})
        url = f"{SITE}/papers/{key}/" if key in summaries else (f"https://doi.org/{b['doi']}" if b["doi"] else "")
        label = b["short"]
        if kind == "citet" and " " in label:
            name, year = label.rsplit(" ", 1)
            label = f"{name} ({year})"
        return f"[[{url}][{label}]]" if url else label

    def rep(m):
        # Keys may contain "." and ":", so a citation that ends a sentence
        # captures the full stop; give it back.
        raw = m.group(2)
        tail = raw[len(raw.rstrip(".:")):]
        kind, keys = m.group(1), raw[:len(raw) - len(tail)].split(",")
        parts = [one(k, kind) for k in keys]
        cited = "(" + "; ".join(parts) + ")" if kind in ("citep", "cite") else ", ".join(parts)
        return cited + tail
    return CITE.sub(rep, text)


def link_files(text, here, wiki):
    """Org file links between wiki articles -> site URLs."""
    def rep(m):
        target = (here / m.group(1)).resolve()
        label = m.group(2) or target.stem
        try:
            rel = target.relative_to(wiki)
        except ValueError:
            return label
        kind = rel.parts[0]
        if kind == "summaries":
            return f"[[{SITE}/papers/{target.stem}/][{label}]]"
        if kind == "concepts":
            return f"[[{SITE}/papers/topics/{target.stem}/][{label}]]"
        return label
    return FILE_LINK.sub(rep, text)


def find_pandoc():
    """pandoc itself if installed; else the copy bundled with Quarto. `quarto pandoc`
    also works but starts Quarto's runtime on every call, which is slow here."""
    exe = shutil.which("pandoc")
    if exe:
        return [exe]
    quarto = shutil.which("quarto")
    if quarto:
        for cand in Path(quarto).resolve().parent.parent.glob("**/tools/*/pandoc"):
            if cand.is_file():
                return [str(cand)]
        return [quarto, "pandoc"]
    sys.exit("export_crucible: needs pandoc (or quarto) on PATH")


PANDOC = None


def org_to_md(text):
    global PANDOC
    PANDOC = PANDOC or find_pandoc()
    r = subprocess.run(PANDOC + ["-f", "org", "-t", "gfm", "--wrap=none"],
                       input=text, capture_output=True, text=True, check=True)
    return r.stdout.replace(f"]({SITE}/", "](/")


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)


def clean_generated():
    for f in PAPERS.rglob("index.qmd"):
        if f.read_text().find(GENERATED) >= 0:
            f.unlink()
    for d in sorted(PAPERS.rglob("*"), reverse=True):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()


def main(project):
    wiki = project / ".crucible" / "wiki"
    bib = bib_entries(project / ".crucible" / "references.bib")
    summaries = {p.stem for p in (wiki / "summaries").glob("*.org")}
    PAPERS.mkdir(exist_ok=True)
    clean_generated()
    index = {}
    disclaimer = ("::: {.callout-note appearance=\"simple\"}\n"
                  "This summary was written by a language model from the paper and has not been "
                  "checked line by line. Rely on the [published paper]({url}) for details.\n:::\n")

    for f in sorted((wiki / "summaries").glob("*.org")):
        title, props, tags, body = parse_org(f)
        key = f.stem
        doi = props.get("DOI", "") or bib.get(key, {}).get("doi", "")
        year = props.get("YEAR", "")
        journal = props.get("JOURNAL", "")
        body = link_files(link_citations(body, bib, summaries), f.parent, wiki)
        # The first paragraph is the full citation; give it its own block.
        cite, _, rest = body.partition("\n\n")
        md = org_to_md(rest)
        doi_url = f"https://doi.org/{doi}" if doi else ""
        cats = [t for t in tags if t != "summary"]
        out = ["---",
               f"title: {yaml_str(title)}",
               f"description: {yaml_str(f'{journal} ({year})')}",
               f"date: {year or '1900'}-01-01",
               "date-format: YYYY",
               f"categories: {json.dumps(cats)}",
               f"doi: {yaml_str(doi)}" if doi else "",
               "toc: true",
               "---",
               GENERATED,
               "",
               "::: {.paper-citation}",
               org_to_md(cite).strip(),
               ":::",
               "",
               f"[Read the paper]({doi_url}){{.btn .btn-primary .btn-sm}} " if doi_url else "",
               "",
               disclaimer.replace("{url}", doi_url or "#"),
               md]
        dest = PAPERS / key / "index.qmd"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text("\n".join(x for x in out if x is not None) + "\n")
        if doi:
            index[doi.lower()] = f"/papers/{key}/"

    for f in sorted((wiki / "concepts").glob("*.org")):
        title, props, tags, body = parse_org(f)
        body = link_files(link_citations(body, bib, summaries), f.parent, wiki)
        keys = props.get("SOURCE_KEYS", "").split()
        papers = [f"- [{bib.get(k, {}).get('short', k)}](/papers/{k}/)" for k in keys if k in summaries]
        out = ["---",
               f"title: {yaml_str(title)}",
               'description: "A research topic across the group’s papers."',
               "toc: true",
               "---",
               GENERATED,
               "",
               org_to_md(body)]
        if papers:
            out += ["", "## Papers on this topic", ""] + papers
        dest = PAPERS / "topics" / f.stem / "index.qmd"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text("\n".join(out) + "\n")

    # Topic links for papers/index.qmd: a plain list (a listing of cards would
    # put <h5> headings straight after an <h2>)
    topics = []
    for f in sorted((wiki / "concepts").glob("*.org"), key=lambda f: parse_org(f)[0].lower()):
        topics.append(f'<li><a href="topics/{f.stem}/">{parse_org(f)[0]}</a></li>')
    (ROOT / "_generated").mkdir(exist_ok=True)
    (ROOT / "_generated" / "topics.md").write_text(
        "```{=html}\n<ul class=\"topic-list\">\n" + "\n".join(topics) + "\n</ul>\n```\n")

    (ROOT / "data" / "papers-index.json").write_text(json.dumps(index, indent=1, sort_keys=True) + "\n")
    n_topics = len(list((wiki / "concepts").glob("*.org")))
    print(f"export_crucible: {len(summaries)} paper summaries, {n_topics} topics -> {PAPERS}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "Dropbox" / "kitchingroup-papers")
